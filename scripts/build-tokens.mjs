// Generates src/design-system/tokens.css from src/design-system/tokens.json.
// tokens.json is the source of truth; run `npm run tokens` after editing it.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "design-system");
const t = JSON.parse(readFileSync(join(root, "tokens.json"), "utf8"));

const light = [];
const dark = [];
const fixed = [];

for (const tok of t.color.tokens) {
  light.push(`  --${tok.name}: ${tok.value.light};`);
  dark.push(`  --${tok.name}: ${tok.value.dark};`);
}
for (const tok of t.shadow.tokens) {
  light.push(`  --${tok.name}: ${tok.value.light};`);
  dark.push(`  --${tok.name}: ${tok.value.dark};`);
}
fixed.push(`  --font-sans: ${t.type.families.sans};`);
fixed.push(`  --font-mono: ${t.type.families.mono};`);
for (const group of ["spacing", "radius", "size", "zIndex"]) {
  for (const tok of t[group].tokens) fixed.push(`  --${tok.name}: ${tok.value};`);
}

const typeClasses = [];
for (const group of t.type.groups) {
  const family = group.family === "mono" ? "var(--font-mono)" : "var(--font-sans)";
  for (const s of group.styles) {
    const lines = [
      `font-family: ${family}`,
      `font-size: ${s.fontSize}`,
      `line-height: ${s.lineHeight}`,
      `font-weight: ${s.fontWeight}`,
    ];
    if (s.letterSpacing) lines.push(`letter-spacing: ${s.letterSpacing}`);
    if (s.name === "overline") lines.push("text-transform: uppercase");
    if (group.family === "mono") lines.push("font-variant-numeric: tabular-nums");
    typeClasses.push(`.t-${s.name} { ${lines.join("; ")}; }`);
  }
}

const css = `/* Generated by scripts/build-tokens.mjs from tokens.json. Do not edit by hand. */
:root {
${fixed.join("\n")}
}

:root, [data-theme="light"] {
${light.join("\n")}
}

[data-theme="dark"] {
${dark.join("\n")}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${dark.map((l) => "  " + l).join("\n")}
    color-scheme: dark;
  }
}

/* Type styles */
${typeClasses.join("\n")}
`;

writeFileSync(join(root, "tokens.css"), css);
console.log("Wrote", join(root, "tokens.css"));
